def th(n):
    """7000 -> '7 000', the way the slides print it."""
    return f"{n:,}".replace(",", " ")


def tth(n):
    """The same for MathTex."""
    return f"{n:,}".replace(",", r"\,")


def signed(v, d=2):
    if round(v, d) == 0 and v >= 0:
        return f"{0:.{d}f}"
    return f"{v:+.{d}f}".replace("-", "−")


def auc(s, y):
    r = np.argsort(np.argsort(s)) + 1.0
    n1 = y.sum(); n0 = len(y) - n1
    return (r[y == 1].sum() - n1 * (n1 + 1) / 2) / (n1 * n0)


def churn_logistic():
    """The plain logistic regression a student fits on churn.csv, every column in,
    by Newton's method. Reference levels as in the recipe, so the coefficients
    read as pushes: one-year contract, DSL, bank transfer, central region."""
    rows = list(csv.DictReader(open(CHURN_CSV)))
    is_ = lambda c, v: np.array([r[c] == v for r in rows], float)
    nm = lambda c: np.array([float(r[c]) for r in rows])
    cols = {"int": np.ones(len(rows)), "m2m": is_("contract", "month-to-month"), "2yr": is_("contract", "two-year"),
            "fibre": is_("internet", "fibre"), "nonet": is_("internet", "none"),
            "techsup": is_("tech_support", "yes"), "security": is_("online_security", "yes"),
            "tv": is_("streaming_tv", "yes"), "paperless": is_("paperless", "yes"),
            "echeck": is_("payment", "e-check"), "card": is_("payment", "card"), "mailed": is_("payment", "mailed check"),
            "senior": nm("senior"), "partner": is_("partner", "yes"), "dependents": is_("dependents", "yes"),
            "lines": nm("phone_lines"), "calls": nm("support_calls"), "late": nm("late_payments"),
            "gb": nm("data_gb"), "referred": is_("referred", "yes"), "north": is_("region", "north"),
            "south": is_("region", "south"), "islands": is_("region", "islands"),
            "charge": nm("monthly_charge"), "tenure": nm("tenure_months")}
    X = np.column_stack(list(cols.values()))
    y = np.array([r["churn"] == "yes" for r in rows], float)
    b = np.zeros(X.shape[1])
    for _ in range(30):
        p = 1 / (1 + np.exp(-X @ b)); w = p * (1 - p)
        b = b + np.linalg.solve(X.T @ (X * w[:, None]), X.T @ (y - p))
    return dict(zip(cols, b)), len(rows)


