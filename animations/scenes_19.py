# ================================================================ 5. autoencoder = PCA
class AutoencoderPCA(Stage):
    """Sixty patients, systolic and diastolic pressure. A linear autoencoder,
    2 -> 1 -> 2, trained here by gradient descent from a bad start: its line turns
    and its error falls, step by step, until it sits on PCA's first component,
    with exactly the variance PCA leaves out as its error."""

    WAIT_SCALE = 1.0
    PLAY_SCALE = 1.0

    def construct(self):
        rng = np.random.default_rng(3)
        n = 60
        sbp = rng.normal(132, 14, n)
        dbp = 82 + 0.45 * (sbp - 132) + rng.normal(0, 5.5, n)
        X = np.column_stack([sbp, dbp])
        mu = X.mean(0)
        C = X - mu

        XR, YR = (90, 180), (60, 105)
        ax = Axes(x_range=[*XR, 30], y_range=[*YR, 15], x_length=6.3, y_length=6.3 * (YR[1] - YR[0]) / (XR[1] - XR[0]),
                  axis_config={"color": MUTED, "include_tip": False, "stroke_width": 1.4}).to_edge(LEFT, buff=1.0).shift(UP * 0.7)
        xt = VGroup(*[label(str(v), 20, MUTED).next_to(ax.c2p(v, YR[0]), DOWN, buff=0.12) for v in range(XR[0], XR[1] + 1, 30)])
        yt = VGroup(*[label(str(v), 20, MUTED).next_to(ax.c2p(XR[0], v), LEFT, buff=0.12) for v in range(YR[0], YR[1] + 1, 15)])
        xl = label("systolic (mmHg)", 22, MUTED).next_to(xt, DOWN, buff=0.15)
        yl = label("diastolic", 22, MUTED).rotate(PI / 2).next_to(yt, LEFT, buff=0.12)
        self.play(Create(ax), FadeIn(xt), FadeIn(yt), FadeIn(xl), FadeIn(yl), run_time=1.0)
        dots = VGroup(*[Dot(ax.c2p(*p), radius=0.055, color=SKY) for p in X])
        self.play(FadeIn(dots, lag_ratio=0.03), run_time=1.4)
        self.caption(label(f"{n} patients: systolic and diastolic blood pressure", 26).move_to(SLOT))
        self.wait(2.4)

        # the network, top right: two in, one number, two out
        def node(p, c):
            return Dot(p, radius=0.13, color=c)
        ins = [node([1.85, 3.35, 0], CREAM), node([1.85, 2.55, 0], CREAM)]
        hid = node([3.95, 2.95, 0], GOLD)
        outs = [node([6.05, 3.35, 0], CREAM), node([6.05, 2.55, 0], CREAM)]
        wires = VGroup(*[Line(a.get_center(), hid.get_center(), stroke_width=1.4, color=MUTED) for a in ins],
                       *[Line(hid.get_center(), b.get_center(), stroke_width=1.4, color=MUTED) for b in outs])
        tags = VGroup(label("SBP", 18, MUTED).next_to(ins[0], LEFT, buff=0.12), label("DBP", 18, MUTED).next_to(ins[1], LEFT, buff=0.12),
                      label("SBP", 18, MUTED).next_to(outs[0], RIGHT, buff=0.12), label("DBP", 18, MUTED).next_to(outs[1], RIGHT, buff=0.12),
                      label("one number", 18, GOLD).next_to(hid, DOWN, buff=0.22))
        net = VGroup(wires, *ins, hid, *outs, tags)
        self.play(FadeIn(net), run_time=1.0)
        self.caption(label("a network that must give back its own input, through one number", 26).move_to(SLOT))
        self.wait(3.0)

        def seg(d):
            """The line through the average patient along d, clipped to the plot."""
            d = d / np.linalg.norm(d)
            lo, hi = -1e9, 1e9
            for j, (a, b) in enumerate((XR, YR)):
                if abs(d[j]) > 1e-9:
                    t1, t2 = sorted(((a - mu[j]) / d[j], (b - mu[j]) / d[j]))
                    lo, hi = max(lo, t1), min(hi, t2)
            return ax.c2p(*(mu + lo * d)), ax.c2p(*(mu + hi * d))

        def deg(d):
            return np.degrees(np.arctan2(d[1], d[0])) % 180

        # gradient descent on mean ||x - v (w.x)||^2, from a nearly vertical start
        w, v, lr = np.array([-0.2, 1.0]), np.array([-0.2, 1.0]), 0.0016
        SHOW = [0, 3, 5, 8, 12, 25, 300]
        snaps = {}
        for step in range(SHOW[-1] + 1):
            z = C @ w
            R = C - np.outer(z, v)
            if step in SHOW:
                snaps[step] = ((R ** 2).sum(1).mean(), v.copy(), w.copy())
            gv = -2 / n * R.T @ z
            gw = -2 / n * C.T @ (R @ v)
            w, v = w - lr * gw, v - lr * gv

        CX, TOP = [1.45, 4.2, 6.55], 1.6
        heads = VGroup(label("step", 22, MUTED).move_to([0, TOP, 0]).align_to([CX[0], 0, 0], LEFT),
                       label("error (mmHg²)", 22, MUTED).move_to([0, TOP, 0]).align_to([CX[1], 0, 0], RIGHT),
                       label("angle", 22, MUTED).move_to([0, TOP, 0]).align_to([CX[2], 0, 0], RIGHT))
        L0, v0, _ = snaps[0]
        line = Line(*seg(v0), color=GOLD, stroke_width=4)
        self.play(Create(line), FadeIn(heads), run_time=1.0)
        rows = VGroup()

        def log(step):
            L, vv, _ = snaps[step]
            y = TOP - 0.5 - 0.42 * len(rows)
            r = VGroup(label(str(step), 22, CREAM).move_to([0, y, 0]).align_to([CX[0], 0, 0], LEFT),
                       label(f"{L:.1f}", 22, GOLD).move_to([0, y, 0]).align_to([CX[1], 0, 0], RIGHT),
                       label(f"{deg(vv):.1f}°", 22, GOLD).move_to([0, y, 0]).align_to([CX[2], 0, 0], RIGHT))
            anims = [FadeIn(r, shift=RIGHT * 0.12)]
            if len(rows):
                anims.append(rows[-1][1:].animate.set_color(CREAM))
            rows.add(r)
            return anims

        self.play(*log(0), run_time=0.6)
        self.caption(label(f"the one number is a line: start badly, almost vertical. Error {L0:.0f}", 26).move_to(SLOT))
        self.wait(3.0)
        self.caption(label("gradient descent turns the line, step by step, and the error falls", 26).move_to(SLOT))
        for step in SHOW[1:]:
            self.play(Transform(line, Line(*seg(snaps[step][1]), color=GOLD, stroke_width=4)), *log(step), run_time=1.0)
            self.wait(0.9 if step < SHOW[-2] else 1.4)
        L_end, v_end, w_end = snaps[SHOW[-1]]
        self.caption(label(f"by step {SHOW[-1]} it has stopped: error {L_end:.1f}, the line at {deg(v_end):.1f}°", 26).move_to(SLOT))
        self.wait(3.0)

        # PCA, computed directly
        lam, V = np.linalg.eigh(C.T @ C / n)
        pc1 = V[:, 1]
        pca = DashedLine(*seg(pc1), color=SKY, stroke_width=4, dash_length=0.12)
        box = VGroup(label(f"autoencoder line: {deg(v_end):.1f}°", 24, GOLD),
                     label(f"PCA, first component: {deg(pc1):.1f}°", 24, SKY),
                     VGroup(label("variance PCA leaves out:", 24, SKY),
                            MathTex(rf"\lambda_2 = {lam[0]:.1f}", color=SKY, font_size=34)).arrange(RIGHT, buff=0.2)
                     ).arrange(DOWN, buff=0.25, aligned_edge=LEFT).move_to([0, 2.95, 0]).align_to([1.3, 0, 0], LEFT)
        self.play(FadeOut(net), run_time=0.6)
        self.play(Create(pca), FadeIn(box[0]), FadeIn(box[1]), run_time=1.2)
        self.caption(label("now PCA on the same patients, computed directly: the same line", 26).move_to(SLOT))
        self.wait(3.2)
        self.play(FadeIn(box[2]), run_time=0.7)
        self.caption(label(f"and the error left, {L_end:.1f}, is exactly the variance PCA drops", 26).move_to(SLOT))
        self.wait(3.4)

        rec = mu + np.outer(C @ w_end, v_end)
        gaps = VGroup(*[Line(ax.c2p(*X[i]), ax.c2p(*rec[i]), stroke_width=1.4, color=CREAM, stroke_opacity=0.6)
                        for i in range(n)])
        self.play(Create(gaps, lag_ratio=0.02), run_time=1.6)
        self.caption(label("each patient comes back as a point on the line: the gaps are the error", 26).move_to(SLOT))
        self.wait(3.2)
        self.caption(label("linear autoencoder = PCA: the one number is overall blood pressure", 26, GOLD).move_to(SLOT))
        self.wait(4.0)
